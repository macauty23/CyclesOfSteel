import type { AttackProfile, EnemyDefinition, EnemyId, RegionId } from "../core/types";

function meleeAttack(config: {
  name: string;
  shape: AttackProfile["shape"];
  attackClass: AttackProfile["attackClass"];
  damage: number;
  range: number;
  width: number;
  windup: number;
  active: number;
  recovery: number;
  lunge: number;
  staminaCost: number;
  commitWeight: number;
  drift: number;
  tint: number;
  displacement: number;
  controlLossMs: number;
  interruptChance: number;
  hitstopMs: number;
  cameraShake: number;
}): AttackProfile {
  return {
    ...config,
    delivery: "melee",
    impact: {
      displacement: config.displacement,
      controlLossMs: config.controlLossMs,
      interruptChance: config.interruptChance,
      hitstopMs: config.hitstopMs,
      cameraShake: config.cameraShake
    }
  };
}

function rangedAttack(config: {
  name: string;
  damage: number;
  range: number;
  width: number;
  windup: number;
  active: number;
  recovery: number;
  tint: number;
}): AttackProfile {
  return {
    name: config.name,
    shape: "thrust",
    attackClass: "standard",
    delivery: "ranged",
    damage: config.damage,
    range: config.range,
    width: config.width,
    windup: config.windup,
    active: config.active,
    recovery: config.recovery,
    lunge: 0,
    staminaCost: 10,
    commitWeight: 0.28,
    drift: 0.24,
    tint: config.tint,
    impact: {
      displacement: 168,
      controlLossMs: 92,
      interruptChance: 0.24,
      hitstopMs: 16,
      cameraShake: 0.0018
    }
  };
}

function defineEnemy(definition: EnemyDefinition): EnemyDefinition {
  return definition;
}

function cloneAttack(attack: AttackProfile): AttackProfile {
  return {
    ...attack,
    impact: {
      ...attack.impact
    }
  };
}

type AttackProfilePatch = Partial<Omit<AttackProfile, "impact">> & {
  impact?: Partial<AttackProfile["impact"]>;
};

function mergeAttack(base: AttackProfile, patch: AttackProfilePatch): AttackProfile {
  return {
    ...cloneAttack(base),
    ...patch,
    impact: {
      ...base.impact,
      ...patch.impact
    }
  };
}

function variantEnemy(
  baseId: EnemyId,
  patch: Omit<Partial<EnemyDefinition>, "lightAttack" | "heavyAttack"> & {
    id: EnemyId;
    name: string;
    summary: string;
    lightAttack?: AttackProfilePatch;
    heavyAttack?: AttackProfilePatch;
  }
): EnemyDefinition {
  const base = ENEMY_DEFINITIONS[baseId];

  return {
    ...base,
    ...patch,
    lightAttack: patch.lightAttack ? mergeAttack(base.lightAttack, patch.lightAttack) : cloneAttack(base.lightAttack),
    heavyAttack: patch.heavyAttack ? mergeAttack(base.heavyAttack, patch.heavyAttack) : cloneAttack(base.heavyAttack)
  };
}

